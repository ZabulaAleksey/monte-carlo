export type Locale = "en" | "ru" | "uk" | "be";
export const supportedLocales = [
  { code: "en" as const, name: "English", intl: "en-US" },
  { code: "ru" as const, name: "Русский", intl: "ru-RU" },
  { code: "uk" as const, name: "Українська", intl: "uk-UA" },
  { code: "be" as const, name: "Беларуская", intl: "be-BY" },
];

const catalogs: Record<Locale, Messages> = { en, ru, uk, be };
const STORAGE_KEY = "montecarlo.locale.v1";

interface I18nValue {
  locale: Locale;
  intlLocale: string;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue>({
  locale: "en",
  intlLocale: "en-US",
  setLocale: () => undefined,
  t: (key, values) => interpolate(en[key], values),
});

function interpolate(
  message: string,
  values: Record<string, string | number> = {},
): string {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

function isLocale(value: string | null): value is Locale {
  return supportedLocales.some(({ code }) => code === value);
}

export function I18nProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [locale, setLocaleState] = useState<Locale | null>(null);

  useEffect(() => {
    let stored: string | null = null;
    try {
      stored = window.localStorage.getItem(STORAGE_KEY);
    } catch {
      // Storage can be unavailable in privacy-restricted browser contexts.
    }
    setLocaleState(isLocale(stored) ? stored : "en");
  }, []);

  const setLocale = useCallback((nextLocale: Locale): void => {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
    } catch {
      // Keep the in-memory locale usable even when persistence is blocked.
    }
  }, []);

  const resolvedLocale = locale ?? "en";
  const intlLocale = supportedLocales.find((item) => item.code === resolvedLocale)?.intl ?? "en-US";

  useEffect(() => {
    if (locale === null) return;
    document.documentElement.lang = intlLocale;
    document.documentElement.dataset.locale = locale;
  }, [intlLocale, locale]);

  const value = useMemo<I18nValue>(() => {
    return {
      locale: resolvedLocale,
      intlLocale,
      setLocale,
      t: (key, values) => interpolate(catalogs[resolvedLocale][key] ?? en[key], values),
    };
  }, [intlLocale, resolvedLocale, setLocale]);

  if (locale === null) {
    return <div aria-busy="true" className="locale-bootstrap"><span /></div>;
  }

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
